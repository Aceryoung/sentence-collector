export async function POST() {
  const admin = await getAdminUser();
  if (!admin) {
    return NextResponse.json({ error: "권한이 없습니다." }, { status: 401 });
  }

  const supabase = await createClient();
  let updated = 0;

  for (const [word, description] of Object.entries(DEFINITIONS)) {
    const { error, count } = await supabase
      .from("daily_words")
      .update({ description })
      .eq("word", word)
      .is("description", null);

    if (!error && count && count > 0) updated++;
  }

  return NextResponse.json({ updated, total: Object.keys(DEFINITIONS).length });
}
